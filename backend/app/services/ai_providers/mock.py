"""Mock AI Provider for testing and staging."""

import asyncio
from typing import Optional

from app.schemas.ai_gateway import (
    AIRequest,
    AIResponse,
    AIProviderConfig,
    AIUsage,
)
from app.services.ai_providers.base import AIProvider, AIProviderError


class MockProvider(AIProvider):
    """Mock AI provider that returns predetermined responses for testing."""

    def __init__(self, config: AIProviderConfig):
        super().__init__(config)

    @property
    def provider_name(self) -> str:
        return "mock"

    async def initialize(self) -> None:
        """Initialize the mock provider."""
        self._client = True  # Just a placeholder
        pass

    async def close(self) -> None:
        """Close the mock provider."""
        self._client = None
        pass

    async def generate(self, request: AIRequest) -> AIResponse:
        """Generate a mock response."""
        # Simulate some processing time
        await asyncio.sleep(0.01)

        # Return a simple mock response based on the last user message
        last_message = request.messages[-1].content if request.messages else ""

        # Simple response based on the request type
        if "ticket" in last_message.lower() or "analyze" in last_message.lower():
            content = '{"summary": "Mock analysis: This appears to be a test ticket.", "suggested_priority": "Medium", "suggested_category": "General", "confidence": 0.9}'
        elif "summarize" in last_message.lower():
            content = "Mock summary: This is a test summary generated by the mock provider."
        elif "classify" in last_message.lower():
            content = '{"category": "General", "confidence": 0.95}'
        else:
            content = f"Mock response to: {last_message[:100]}..."

        return AIResponse(
            content=content,
            provider="mock",
            model=self.config.model,
            citations=[],
            usage=AIUsage(prompt_tokens=10, completion_tokens=20, total_tokens=30),
            metadata={"elapsed_seconds": 0.01, "mock": True},
        )


# Export for factory
MockProvider = MockProvider